func (f *fixture) path(rel string) string { return filepath.Join(f.root, filepath.FromSlash(rel)) }

func (f *fixture) write(rel, content string) {
	f.t.Helper()
	writeFile(f.t, f.path(rel), content)
}

func writeFile(t *testing.T, path, content string) {
	t.Helper()
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
		t.Fatal(err)
	}
}

func (f *fixture) input(rel string) fixtureInput {
	f.t.Helper()
	data, err := os.ReadFile(f.path(rel))
	if err != nil {
		f.t.Fatal(err)
	}
	return fixtureInput{Path: rel, Blob: f.gitOut("rev-parse", "HEAD:"+rel), SHA256: sha(data)}
}

func testGit(t *testing.T, root string, args ...string) (string, error) {
	t.Helper()
	cmd := exec.Command("git", append([]string{"-C", root}, args...)...)
	cmd.SysProcAttr = &syscall.SysProcAttr{HideWindow: true, CreationFlags: createNoWindow}
	cmd.Env = childEnvironment(os.Environ())
	out, err := cmd.CombinedOutput()
	return strings.TrimSpace(string(out)), err
}

func (f *fixture) git(args ...string) {
	f.t.Helper()
	if out, err := testGit(f.t, f.root, args...); err != nil {
		f.t.Fatalf("git %v: %v\n%s", args, err, out)
	}
}

