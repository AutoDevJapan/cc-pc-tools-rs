//! Router hints do not define the capabilities of an ordinary scheduled job.
use cc_job_policy::capability_scope::{
    constrained as explicit_field, fixed as contract, legacy as ambiguous_legacy_source,
    owner as owner_scope,
};
use serde_json::{Value, json};

/// A fresh Console conversation may retain a fixed scope, never its model,
/// prompt or session. Re-read the actual current worker instead of trusting the
/// identifier or copied capability values supplied by the adapter.
pub(crate) fn source<'a>(
    item: &Value,
    jobs: &'a [Value],
    ps: &crate::policy::Processes,
    timestamp: f64,
) -> crate::common::Result<Option<&'a Value>> {
    use crate::{common::*, policy};
    let id = &item["scheduler"]["console_request"]["options"]["scope_contract_source_job"];
    if id.is_null() {
        return Ok(None);
    }
    let source = jobs
        .iter()
        .find(|job| !s(id).is_empty() && job["id"] == *id)
        .ok_or(Error("InputRejected"))?;
    let receipt = &item["worker_receipt"];
    let generation = item["resume_generation"].as_u64().unwrap_or(0);
    let generation_matches = if !receipt["job"].is_null() {
        receipt["job"] == *id && receipt["generation"].as_u64() == Some(generation)
    } else {
        generation == 0 || source["todo_resume_generation"].as_u64() == Some(generation)
    };
    if !contract(source)
        || !matches!(
            s(&source["status"]),
            "succeeded" | "failed" | "lost" | "cancelled" | "canceled"
        )
        || !crate::preparation::owns_workspace(item, source)
        || !arr(&item["jobs"]).contains(id)
        || !(source["todo_id"] == item["id"]
            || arr(&source["related_todo_ids"]).contains(&item["id"]))
        || !generation_matches
        || (source["todo_resume_generation"].is_u64()
            && source["todo_resume_generation"].as_u64() != Some(generation))
        || crate::preparation::workspace_source(item, jobs)
            .is_none_or(|current| current["id"] != *id)
        || s(&source["cwd"]).is_empty()
        || norm(s(&source["cwd"])) != norm(s(&item["scheduler"]["worktree"]))
        || !cc_job_policy::subwork_continuation::unheld(item, source)
        || jobs.iter().any(|job| {
            (job["todo_id"] == item["id"] || arr(&item["jobs"]).contains(&job["id"]))
                && (policy::live(job) || policy::alive(job, ps, timestamp))
        })
    {
        return Err(Error("InputRejected"));
    }
    Ok(Some(source))
}

/// Only actual fixed contracts retain a launcher's historical capability tuple.
/// Ordinary finite result bindings identify work, not a restricted tool set.
pub(crate) fn apply(item: &Value, source: Option<&Value>, selection: &mut Value) {
    let options = &item["scheduler"]["console_request"]["options"];
    let selected = selection.clone();
    // Carry only the scope of a real source contract across this generation's
    // preparation/launch boundary; a previous cached generation cannot bind it.
    let receipt = &selected["scope_contract"];
    let recorded = (receipt.is_object()
        && receipt["todo_id"] == item["id"]
        && receipt["launch_key"]
            .as_str()
            .is_some_and(|key| !key.is_empty())
        && receipt["launch_key"] == item["scheduler"]["key"]
        && receipt["spec"]
            .as_str()
            .is_some_and(|spec| !spec.is_empty())
        && receipt["spec"] == item["spec"]
        && receipt["source_job"].is_string()
        && receipt["sandbox"].is_string()
        && receipt["mcp_profile"].is_string())
    .then_some(receipt);
    let source_contract = source.filter(|value| contract(value));
    let fixed = item["product_review_allocation"].is_object()
        || (item["subwork_continuation"].is_object()
            && !cc_job_policy::subwork_continuation::stale_request(item))
        || contract(item)
        || contract(&item["scheduler"])
        || contract(selection)
        || source_contract.is_some()
        || recorded.is_some();
    let mut scope_source = "launcher";
    for field in ["sandbox", "mcp_profile"] {
        // Current saved inputs remain explicit unless they say they were
        // generated by a launcher/router. Unmarked cached selections do not.
        let current = [item, options].into_iter().find(|value| {
            !value[field].is_null()
                && (explicit_field(value, field)
                    || (value["capability_provenance_version"] != 1 && value["scope_source"].is_null()))
        });
        let fixed_value = if fixed {
            (contract(&selected) && !selected[field].is_null())
                .then_some(&selected)
                .or_else(|| source_contract.filter(|value| !value[field].is_null()))
                .or(recorded)
                .or_else(|| (!selected[field].is_null()).then_some(&selected))
                .or_else(|| source.filter(|value| !value[field].is_null()))
        } else {
            None
        };
        let chosen = if fixed {
            current
                .filter(|current| fixed_value.is_none_or(|bound| current[field] == bound[field]))
                .or(fixed_value)
        } else {
            current
                .or_else(|| {
                    (explicit_field(&selected, field) && !selected[field].is_null())
                        .then_some(&selected)
                })
                .or_else(|| {
                    source.filter(|value| {
                        (explicit_field(value, field) || ambiguous_legacy_source(value, field))
                            && !value[field].is_null()
                    })
                })
        };
        selection[field] = chosen.map_or_else(|| json!("inherit"), |value| value[field].clone());
        let durable = chosen.is_some_and(|value| {
            explicit_field(value, field)
                || current.is_some_and(|current| std::ptr::eq(current, value))
                || (!contract(value) && ambiguous_legacy_source(value, field))
        });
        if let Some(value) = chosen.filter(|value| owner_scope(value) && durable) {
            scope_source = value["scope_source"].as_str().unwrap();
        } else if durable && scope_source == "launcher" {
            // The caller deliberately retained this tuple. This is not an
            // assertion that its historical origin was an owner instruction.
            scope_source = "caller_constraint";
        }
        selection["explicit_capability_constraints"][field] = json!(durable);
        // Unknown pre-provenance standalone records are retained conservatively,
        // without claiming that an owner or caller explicitly chose the scope.
        selection["legacy_capability_constraints"][field] = json!(chosen.is_some_and(|value| {
            value["legacy_capability_constraints"][field] == true
                || source.is_some_and(|source| {
                    std::ptr::eq(source, value) && ambiguous_legacy_source(value, field)
                })
        }));
    }
    if item["product_review_allocation"].is_object() {
        selection["sandbox"] = json!("read-only");
        if selection["mcp_profile"] == "inherit" {
            selection["mcp_profile"] = json!("minimal");
        }
    }
    if item["scheduler"]["console_request"]["read_only"] == true {
        selection["sandbox"] = json!("read-only");
        selection["explicit_capability_constraints"]["sandbox"] = json!(true);
        scope_source = if options["scope_source"] == "owner_marker" {
            "owner_marker"
        } else {
            "owner_request"
        };
    }
    if cc_job_policy::explicit_read_only(item["title"].as_str().unwrap_or("")) {
        selection["sandbox"] = json!("read-only");
        selection["explicit_capability_constraints"]["sandbox"] = json!(true);
        scope_source = "owner_marker";
    }
    selection["scope_source"] = json!(scope_source);
    selection["capability_provenance_version"] = json!(1);
    if let Some(source) = source_contract {
        selection["scope_contract"] = json!({"todo_id":item["id"],
            "launch_key":item["scheduler"]["key"],"spec":item["spec"],
            "source_job":source["id"],"sandbox":selection["sandbox"],
            "mcp_profile":selection["mcp_profile"],"scope_source":selection["scope_source"],
            "capability_provenance_version":1,
            "explicit_capability_constraints":selection["explicit_capability_constraints"]});
    }
}
