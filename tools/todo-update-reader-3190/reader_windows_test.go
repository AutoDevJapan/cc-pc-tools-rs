func TestPinnedFilesResistReplacement(t *testing.T) {
	f := newFixture(t, nil)
	var refused []string
	attempt := func(name string, op func() error) {
		if err := op(); err != nil {
			refused = append(refused, name)
		}
	}
	f.onCapacity = func() {
		attempt("write installed leaf", func() error { return os.WriteFile(f.target, []byte("replaced"), 0o644) })
		attempt("rename installed leaf", func() error { return os.Rename(f.target, f.target+".moved") })
		attempt("delete installed leaf", func() error { return os.Remove(f.target) })
	}
	f.onRecheck = func() {
		attempt("write candidate", func() error { return os.WriteFile(f.path(fixtureCandidateName), []byte("replaced"), 0o644) })
		attempt("rename receipt", func() error { return os.Rename(f.path(fixtureReceiptName), f.path("moved.json")) })
		attempt("write input", func() error { return os.WriteFile(f.path("lib-a/src/lib.rs"), []byte("replaced"), 0o644) })
		attempt("rename source root", func() error { return os.Rename(f.root, f.root+"-moved") })
	}
	got, reason := f.verify()
	if !got.Qualified {
		t.Fatalf("verify rejected %q after refused replacements %v", reason, refused)
	}
	want := []string{"write installed leaf", "rename installed leaf", "delete installed leaf", "write candidate", "rename receipt", "write input", "rename source root"}
	if strings.Join(refused, ",") != strings.Join(want, ",") {
		t.Fatalf("refused %v, want every replacement of pinned evidence refused %v", refused, want)
	}
}

